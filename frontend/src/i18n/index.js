// Convenience getter with fallback to English for any missing key —
// keeps the UI from breaking if a new string hasn't been translated yet.
export function t(lang, key) {
  const dict = I18N[lang]?.ui || I18N.en.ui
  return dict[key] ?? I18N.en.ui[key] ?? key
}
